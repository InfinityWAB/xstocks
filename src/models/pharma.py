from __future__ import annotations

from sqlalchemy import Enum as SqlEnum, Float, ForeignKey, Index, Integer, String
from sqlalchemy.orm import Mapped, mapped_column

from .base import ModelBase, TenantMixin
from .enums import TransferSuggestionStatus


class ControlledSubstanceRegister(TenantMixin, ModelBase):
    """
    Controlled-substance register. sequence_number must be max(previous)+1 with
    no gaps — enforced at the service level (transactional lock), not here
    (the model only exposes the column). Written by StockMovementService on
    every controlled-substance OUT move (spec §3.2-h) — not a dedicated
    "pharma" feature, this is core issue() business logic.
    """

    __tablename__ = "xstock_controlled_substance_registers"

    product_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("xstock_products.id"), nullable=False, index=True
    )
    batch_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("xstock_batches.id"), nullable=False, index=True
    )
    move_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("xstock_moves.id"), nullable=False, unique=True
    )
    sequence_number: Mapped[int] = mapped_column(Integer, nullable=False)
    signatory_id: Mapped[str] = mapped_column(String(36), nullable=False)
    witness_id: Mapped[str] = mapped_column(String(36), nullable=False)
    theoretical_balance_after: Mapped[float] = mapped_column(Float, nullable=False)

    __table_args__ = (
        Index(
            "idx_xstock_csr_tenant_product_seq",
            "tenant_id", "product_id", "sequence_number",
            unique=True,
        ),
    )

    def __repr__(self) -> str:
        return f"<ControlledSubstanceRegister(id={self.id!r}, seq={self.sequence_number!r})>"


class TransferSuggestion(TenantMixin, ModelBase):
    """Inter-site rebalancing suggestion, generated by the engine (spec §3.2-j)."""

    __tablename__ = "xstock_transfer_suggestions"

    product_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("xstock_products.id"), nullable=False, index=True
    )
    source_site_id: Mapped[str] = mapped_column(String(36), nullable=False)
    destination_site_id: Mapped[str] = mapped_column(String(36), nullable=False)
    suggested_quantity: Mapped[float] = mapped_column(Float, nullable=False)
    reason: Mapped[str] = mapped_column(String(255), nullable=False)
    status: Mapped[TransferSuggestionStatus] = mapped_column(
        SqlEnum(TransferSuggestionStatus), nullable=False, default=TransferSuggestionStatus.SUGGESTED
    )

    __table_args__ = (
        Index("idx_xstock_transfer_tenant_product", "tenant_id", "product_id"),
    )

    def __repr__(self) -> str:
        return f"<TransferSuggestion(id={self.id!r}, status={self.status!r})>"
